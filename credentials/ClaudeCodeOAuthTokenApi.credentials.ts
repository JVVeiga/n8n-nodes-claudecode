import type { ICredentialType, INodeProperties } from 'n8n-workflow';

/**
 * A Claude Code OAuth token (`claude setup-token`), used for one execution only.
 *
 * Selected on the node, it becomes `CLAUDE_CODE_OAUTH_TOKEN` in the environment of the CLI
 * subprocess that execution spawns. Unlike an API key this authenticates against a Claude plan, so
 * the Usage node can report that account's limits and reset windows rather than the host's.
 *
 * **No Test button.** A declarative credential test needs an HTTP endpoint that accepts this token,
 * and there is no documented one — the SDK bundle carries an `oauth-2025-04-20` beta identifier,
 * which is a string in a bundle, not a contract. Shipping a test built on that guess would put a red
 * cross on working credentials, which is worse than having no button. The first real run is the
 * test.
 */
export class ClaudeCodeOAuthTokenApi implements ICredentialType {
	name = 'claudeCodeOAuthTokenApi';

	displayName = 'Claude Code OAuth Token API';

	documentationUrl = 'https://docs.claude.com/en/docs/claude-code/sdk';

	properties: INodeProperties[] = [
		{
			displayName: 'OAuth Token',
			name: 'oauthToken',
			type: 'string',
			typeOptions: { password: true },
			default: '',
			required: true,
			placeholder: 'sk-ant-oat01-...',
			description:
				'Generated by running "claude setup-token" on a machine logged into the account. Authenticates against that account\'s Claude plan. This credential has no Test button — the token has no documented HTTP endpoint to test against.',
		},
	];
}
